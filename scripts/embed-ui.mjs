// Embed the built web UI into src/web_assets.h so the payload can serve it
// without touching the filesystem. Run through "make ui".
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { extname, join, relative, sep } from 'node:path';

const ROOT = 'web/dist';
const OUTPUT = 'src/web_assets.h';
const TYPES = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.png': 'image/png',
  '.ico': 'image/x-icon',
  '.woff2': 'font/woff2',
};

function walk(directory) {
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const path = join(directory, entry.name);
    return entry.isDirectory() ? walk(path) : [path];
  });
}

let files;
try {
  files = walk(ROOT).map((path) => ({
    path: '/' + relative(ROOT, path).split(sep).join('/'),
    type: TYPES[extname(path)] ?? 'application/octet-stream',
    data: readFileSync(path),
  }));
} catch (error) {
  console.error(`embed-ui: cannot read ${ROOT}: ${error.message}`);
  console.error('embed-ui: run "make ui" after installing the web dependencies');
  process.exit(1);
}
if (!files.some((file) => file.path === '/index.html')) {
  console.error(`embed-ui: ${ROOT}/index.html is missing`);
  process.exit(1);
}
files.sort((a, b) => (a.path === '/index.html' ? -1 : b.path === '/index.html' ? 1 : a.path.localeCompare(b.path)));

// Octal escapes never swallow the next character, unlike \x.
const literal = (data) => {
  let text = '';
  for (let i = 0; i < data.length; i++) {
    if (i && i % 40 === 0) {
      text += '"\n  "';
    }
    text += '\\' + data[i].toString(8).padStart(3, '0');
  }
  return `"${text}"`;
};

const lines = [
  '/* Generated by scripts/embed-ui.mjs. Do not edit. */',
  '#pragma once',
  '',
  'typedef struct {',
  '  const char *path;',
  '  const char *type;',
  '  const char *data;',
  '  unsigned int length;',
  '} web_asset_t;',
  '',
];

files.forEach((file, index) => {
  lines.push(`static const char web_asset_${index}[] = ${literal(file.data)};`, '');
});
lines.push('static const web_asset_t web_assets[] = {');
files.forEach((file, index) => {
  lines.push(`  {${JSON.stringify(file.path)}, ${JSON.stringify(file.type)}, web_asset_${index}, ${file.data.length}u},`);
});
lines.push('};', '', '#define WEB_ASSET_COUNT ((int)(sizeof(web_assets) / sizeof(web_assets[0])))', '');

writeFileSync(OUTPUT, lines.join('\n'));
console.log(`embed-ui: wrote ${OUTPUT} (${files.length} files, ${statSync(OUTPUT).size} bytes)`);
